const TAG_NAMES = new Map<number, string>();
for (const [name, value] of Object.entries(TAG)) {
  TAG_NAMES.set(value as number, name);
}

const GPS_TAG_NAMES = new Map<number, string>();
for (const [name, value] of Object.entries(GPS_TAG)) {
  GPS_TAG_NAMES.set(value as number, name);
}

export function tagName(tag: number, isGps: boolean): string {
  const name = isGps ? GPS_TAG_NAMES.get(tag) : TAG_NAMES.get(tag);
  return name ?? `Tag 0x${tag.toString(16).padStart(4, "0")}`;
}

